import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	writeFileSync,
} from "node:fs";
import { isAbsolute, relative, resolve, sep } from "node:path";

const repoRoot = resolve(import.meta.dirname, "..");
const pluginsDir = resolve(repoRoot, "plugins");
const generatedDir = resolve(pluginsDir, "generated");
const generatedFile = resolve(generatedDir, "manifests.ts");
const firmwareDir = resolve(repoRoot, "firmware");
const firmwareGeneratedConfigDir = resolve(firmwareDir, "generated");
const firmwareGeneratedIncludeDir = resolve(firmwareDir, "include/generated");
const firmwareGeneratedSourceDir = resolve(firmwareDir, "src/generated");
const firmwarePluginConfigFile = resolve(
	firmwareGeneratedConfigDir,
	"plugins.ini",
);
const firmwarePluginRegistryHeaderFile = resolve(
	firmwareGeneratedIncludeDir,
	"PluginRegistrations.h",
);
const firmwarePluginRegistrySourceFile = resolve(
	firmwareGeneratedSourceDir,
	"PluginRegistrations.cpp",
);
const generatedNotice =
	"Generated by scripts/generate-plugin-registry.mjs. Do not edit manually.";
const pluginCapabilities = new Set(["time", "network", "ha", "touch"]);
const pluginConfigFieldTypes = new Set([
	"text",
	"number",
	"boolean",
	"select",
	"color",
	"image",
]);
const identifierPattern = /^[A-Za-z_][A-Za-z0-9_]*$/;

function validationError(manifestFile, message) {
	return new Error(`Invalid plugin manifest ${manifestFile}: ${message}`);
}

function isObject(value) {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

function assertObject(value, fieldPath, manifestFile) {
	if (!isObject(value)) {
		throw validationError(manifestFile, `${fieldPath} must be an object`);
	}
}

function assertNonEmptyString(value, fieldPath, manifestFile) {
	if (typeof value !== "string" || value.length === 0) {
		throw validationError(
			manifestFile,
			`${fieldPath} must be a non-empty string`,
		);
	}
}

function assertOptionalString(value, fieldPath, manifestFile) {
	if (value !== undefined && typeof value !== "string") {
		throw validationError(manifestFile, `${fieldPath} must be a string`);
	}
}

function assertOptionalBoolean(value, fieldPath, manifestFile) {
	if (value !== undefined && typeof value !== "boolean") {
		throw validationError(manifestFile, `${fieldPath} must be a boolean`);
	}
}

function assertOptionalNumber(value, fieldPath, manifestFile) {
	if (value !== undefined && typeof value !== "number") {
		throw validationError(manifestFile, `${fieldPath} must be a number`);
	}
}

function assertSafeRelativePath(value, fieldPath, manifestFile) {
	assertNonEmptyString(value, fieldPath, manifestFile);

	if (isAbsolute(value) || value.split(/[\\/]/).includes("..")) {
		throw validationError(
			manifestFile,
			`${fieldPath} must be a relative path inside the plugin directory`,
		);
	}
}

function assertSafeInclude(value, fieldPath, manifestFile) {
	assertSafeRelativePath(value, fieldPath, manifestFile);

	if (value.includes('"')) {
		throw validationError(manifestFile, `${fieldPath} cannot contain quotes`);
	}
}

function toPosixPath(filePath) {
	return filePath.split(sep).join("/");
}

function toCppStringLiteral(value) {
	return JSON.stringify(value);
}

function resolveInsideDirectory(rootDir, childPath, fieldPath, manifestFile) {
	const resolvedPath = resolve(rootDir, childPath);
	const relativePath = relative(rootDir, resolvedPath);

	if (relativePath.startsWith("..") || isAbsolute(relativePath)) {
		throw validationError(
			manifestFile,
			`${fieldPath} must stay inside the plugin directory`,
		);
	}

	return resolvedPath;
}

function validatePluginManifest(manifest, manifestFile) {
	assertObject(manifest, "manifest", manifestFile);

	assertNonEmptyString(manifest.id, "id", manifestFile);
	if (!/^[a-z][a-z0-9-]*$/.test(manifest.id)) {
		throw validationError(manifestFile, "id must match /^[a-z][a-z0-9-]*$/");
	}

	assertNonEmptyString(manifest.version, "version", manifestFile);
	assertNonEmptyString(manifest.displayName, "displayName", manifestFile);
	assertNonEmptyString(manifest.description, "description", manifestFile);

	assertObject(manifest.defaultSize, "defaultSize", manifestFile);
	for (const field of ["colSpan", "rowSpan"]) {
		const value = manifest.defaultSize[field];

		if (!Number.isInteger(value) || value < 1 || value > 4) {
			throw validationError(
				manifestFile,
				`defaultSize.${field} must be an integer from 1 to 4`,
			);
		}
	}

	const capabilities =
		manifest.capabilities === undefined ? [] : manifest.capabilities;

	if (!Array.isArray(capabilities)) {
		throw validationError(manifestFile, "capabilities must be an array");
	}

	for (const [index, capability] of capabilities.entries()) {
		if (!pluginCapabilities.has(capability)) {
			throw validationError(
				manifestFile,
				`capabilities[${index}] must be one of time, network, ha, touch`,
			);
		}
	}

	const configFields =
		manifest.configFields === undefined ? [] : manifest.configFields;

	if (!Array.isArray(configFields)) {
		throw validationError(manifestFile, "configFields must be an array");
	}

	for (const [fieldIndex, field] of configFields.entries()) {
		const fieldPath = `configFields[${fieldIndex}]`;

		assertObject(field, fieldPath, manifestFile);
		assertNonEmptyString(field.key, `${fieldPath}.key`, manifestFile);
		assertNonEmptyString(field.label, `${fieldPath}.label`, manifestFile);

		if (!pluginConfigFieldTypes.has(field.type)) {
			throw validationError(
				manifestFile,
				`${fieldPath}.type must be one of text, number, boolean, select, color, image`,
			);
		}

		assertOptionalBoolean(
			field.required,
			`${fieldPath}.required`,
			manifestFile,
		);
		assertOptionalString(
			field.placeholder,
			`${fieldPath}.placeholder`,
			manifestFile,
		);
		assertOptionalString(
			field.description,
			`${fieldPath}.description`,
			manifestFile,
		);
		assertOptionalNumber(field.min, `${fieldPath}.min`, manifestFile);
		assertOptionalNumber(field.max, `${fieldPath}.max`, manifestFile);
		assertOptionalNumber(field.step, `${fieldPath}.step`, manifestFile);

		if (
			field.defaultValue !== undefined &&
			!["string", "number", "boolean"].includes(typeof field.defaultValue)
		) {
			throw validationError(
				manifestFile,
				`${fieldPath}.defaultValue must be a string, number, or boolean`,
			);
		}

		if (field.options !== undefined) {
			if (!Array.isArray(field.options)) {
				throw validationError(
					manifestFile,
					`${fieldPath}.options must be an array`,
				);
			}

			for (const [optionIndex, option] of field.options.entries()) {
				const optionPath = `${fieldPath}.options[${optionIndex}]`;

				assertObject(option, optionPath, manifestFile);
				assertNonEmptyString(option.label, `${optionPath}.label`, manifestFile);
				assertNonEmptyString(option.value, `${optionPath}.value`, manifestFile);
			}
		}
	}

	let firmware = manifest.firmware;
	if (firmware !== undefined) {
		assertObject(firmware, "firmware", manifestFile);

		if (firmware.type !== "platformio-library") {
			throw validationError(
				manifestFile,
				"firmware.type must be platformio-library",
			);
		}

		assertSafeInclude(firmware.include, "firmware.include", manifestFile);
		assertNonEmptyString(
			firmware.renderFunction,
			"firmware.renderFunction",
			manifestFile,
		);

		if (!identifierPattern.test(firmware.renderFunction)) {
			throw validationError(
				manifestFile,
				"firmware.renderFunction must be a C/C++ identifier",
			);
		}

		if (firmware.path !== undefined) {
			assertSafeRelativePath(firmware.path, "firmware.path", manifestFile);
		}

		assertOptionalString(
			firmware.needsSecondTicksFunction,
			"firmware.needsSecondTicksFunction",
			manifestFile,
		);

		if (
			firmware.needsSecondTicksFunction !== undefined &&
			!identifierPattern.test(firmware.needsSecondTicksFunction)
		) {
			throw validationError(
				manifestFile,
				"firmware.needsSecondTicksFunction must be a C/C++ identifier",
			);
		}

		assertOptionalString(
			firmware.handleTouchFunction,
			"firmware.handleTouchFunction",
			manifestFile,
		);

		if (
			firmware.handleTouchFunction !== undefined &&
			!identifierPattern.test(firmware.handleTouchFunction)
		) {
			throw validationError(
				manifestFile,
				"firmware.handleTouchFunction must be a C/C++ identifier",
			);
		}

		firmware = {
			...firmware,
			path: firmware.path ?? ".",
		};
	}

	return {
		...manifest,
		capabilities,
		configFields,
		...(firmware ? { firmware } : {}),
	};
}

function assertUniquePluginIds(pluginEntries) {
	const seenPluginIds = new Set();

	for (const entry of pluginEntries) {
		if (seenPluginIds.has(entry.manifest.id)) {
			throw validationError(
				entry.manifestFile,
				`duplicate plugin id: ${entry.manifest.id}`,
			);
		}

		seenPluginIds.add(entry.manifest.id);
	}
}

function getFirmwareLibraryPath(entry) {
	const firmwarePath = entry.manifest.firmware.path;
	const libraryPath = resolveInsideDirectory(
		entry.pluginDir,
		firmwarePath,
		"firmware.path",
		entry.manifestFile,
	);

	if (!existsSync(libraryPath)) {
		throw validationError(
			entry.manifestFile,
			`firmware.path does not exist: ${firmwarePath}`,
		);
	}

	return libraryPath;
}

function writeWebPluginRegistry(pluginEntries) {
	mkdirSync(generatedDir, { recursive: true });

	writeFileSync(
		generatedFile,
		`// ${generatedNotice}\n\nimport type { PluginManifest } from "@budpy/plugin-sdk";\n\nexport const pluginManifests = ${JSON.stringify(
			pluginEntries.map((entry) => entry.manifest),
			null,
			2,
		)} satisfies PluginManifest[];\n`,
	);
}

function writeFirmwarePluginRegistry(pluginEntries) {
	const firmwarePluginEntries = pluginEntries.filter(
		(entry) => entry.manifest.firmware,
	);
	const includeLines = firmwarePluginEntries
		.map((entry) => `#include "${entry.manifest.firmware.include}"`)
		.join("\n");
	const registrationLines = firmwarePluginEntries
		.map((entry) => {
			const firmware = entry.manifest.firmware;
			const needsSecondTicks = firmware.needsSecondTicksFunction ?? "nullptr";
			const handleTouch = firmware.handleTouchFunction ?? "nullptr";

			return [
				"    {",
				`        ${toCppStringLiteral(entry.manifest.id)},`,
				`        ${firmware.renderFunction},`,
				`        ${needsSecondTicks},`,
				`        ${handleTouch},`,
				"    },",
			].join("\n");
		})
		.join("\n");
	const registrations =
		registrationLines ||
		[
			"    {",
			"        nullptr,",
			"        nullptr,",
			"        nullptr,",
			"        nullptr,",
			"    },",
		].join("\n");

	mkdirSync(firmwareGeneratedIncludeDir, { recursive: true });
	mkdirSync(firmwareGeneratedSourceDir, { recursive: true });

	writeFileSync(
		firmwarePluginRegistryHeaderFile,
		`// ${generatedNotice}\n\n#pragma once\n\n#include "PluginRuntime.h"\n\n#include <stddef.h>\n\nextern const PluginRegistration pluginRegistrations[];\nextern const size_t pluginRegistrationCount;\n`,
	);

	writeFileSync(
		firmwarePluginRegistrySourceFile,
		`// ${generatedNotice}\n\n#include "generated/PluginRegistrations.h"\n\n${includeLines}\n\nconst PluginRegistration pluginRegistrations[] = {\n${registrations}\n};\n\nconst size_t pluginRegistrationCount = ${firmwarePluginEntries.length};\n`,
	);
}

function writeFirmwarePluginConfig(pluginEntries) {
	const libDeps = pluginEntries
		.filter((entry) => entry.manifest.firmware)
		.map((entry) => {
			const libraryPath = getFirmwareLibraryPath(entry);
			const relativeLibraryPath = toPosixPath(
				relative(firmwareDir, libraryPath),
			);

			return `  symlink://${relativeLibraryPath}`;
		})
		.join("\n");

	mkdirSync(firmwareGeneratedConfigDir, { recursive: true });

	writeFileSync(
		firmwarePluginConfigFile,
		`; Generated by scripts/generate-plugin-registry.mjs. Do not edit manually.\n\n[budpy_plugins]\nlib_deps =\n${libDeps}\n`,
	);
}

if (!existsSync(pluginsDir)) {
	throw new Error(`Plugins directory not found: ${pluginsDir}`);
}

const pluginEntries = readdirSync(pluginsDir, { withFileTypes: true })
	.filter((entry) => entry.isDirectory() && entry.name !== "generated")
	.map((entry) => {
		const pluginDir = resolve(pluginsDir, entry.name);
		const manifestFile = resolve(pluginDir, "manifest.json");

		if (!existsSync(manifestFile)) {
			throw new Error(`Missing manifest.json for plugin: ${entry.name}`);
		}

		let manifest;

		try {
			manifest = JSON.parse(readFileSync(manifestFile, "utf8"));
		} catch (error) {
			throw new Error(`Invalid JSON in ${manifestFile}: ${error.message}`);
		}

		return {
			manifest: validatePluginManifest(manifest, manifestFile),
			manifestFile,
			pluginDir,
		};
	})
	.sort((left, right) =>
		String(left.manifest.id).localeCompare(String(right.manifest.id)),
	);

assertUniquePluginIds(pluginEntries);

writeWebPluginRegistry(pluginEntries);
writeFirmwarePluginRegistry(pluginEntries);
writeFirmwarePluginConfig(pluginEntries);
